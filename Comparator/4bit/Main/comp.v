module FBC(
    input [3:0] A,
    input [3:0] B,
    output G,
    output E,
    output L
);

assign G = (A[3] & ~B[3]) | 
           (A[3] ~^ B[3]) & (A[2] & ~B[2]) |
           (A[3] ~^ B[3]) & (A[2] ~^ B[2]) & (A[1] & ~B[1]) |
           (A[3] ~^ B[3]) & (A[2] ~^ B[2]) & (A[1] ~^ B[1]) & (A[0] & ~B[0]);

assign E = (A[3] ~^ B[3]) & (A[2] ~^ B[2]) & (A[1] ~^ B[1]) &
           (A[0] ~^ B[0]);

assign L = (~A[3] & B[3]) |
           (A[3] ~^ B[3]) & (~A[2] & B[2]) |
           (A[3] ~^ B[3]) & (A[2] ~^ B[2]) & (~A[1] & B[1]) |
           (A[3] ~^ B[3]) & (A[2] ~^ B[2]) & (A[1] ~^ B[1]) & (~A[0] & B[0]);

endmodule